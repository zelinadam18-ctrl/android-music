package io.github.rudicilibrasi.pianotrainer.database

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.IO

/**
 * The app's local database (spec §13, §14). Entities for attempts (#51) and progress (#52) are
 * added here; bump [version] and add a migration when the schema changes after release.
 *
 * Build one with [buildPianoDatabase] from a platform builder: `databaseBuilder(context)` on
 * Android, `databaseBuilder()` on iOS.
 */
@Database(
    entities = [MetadataEntity::class, SongProgressEntity::class, PhraseProgressEntity::class],
    version = 1,
    exportSchema = true,
)
@ConstructedBy(PianoDatabaseConstructor::class)
abstract class PianoDatabase : RoomDatabase() {
    abstract fun metadataDao(): MetadataDao

    abstract fun progressDao(): ProgressDao

    companion object {
        const val FILE_NAME = "piano_trainer.db"
    }
}

/** Generated by Room for each platform. */
@Suppress("KotlinNoActualForExpect")
expect object PianoDatabaseConstructor : RoomDatabaseConstructor<PianoDatabase> {
    override fun initialize(): PianoDatabase
}

/** Finishes a platform builder the same way everywhere: bundled SQLite, queries off the main thread. */
fun buildPianoDatabase(builder: RoomDatabase.Builder<PianoDatabase>): PianoDatabase =
    builder
        .setDriver(BundledSQLiteDriver())
        .setQueryCoroutineContext(Dispatchers.IO)
        .build()
