"""Draws the Piano Trainer icon: four white piano keys, two black keys and a gold strip on indigo.

One list of shapes (in the 108x108 Android adaptive-icon viewport) produces the Android vector
foreground and a 512x512 PNG preview (e.g. for a store listing), so the two match.
"""
import struct, sys, zlib

INDIGO = (0x3F, 0x51, 0xB5)
WHITE = (0xFF, 0xFF, 0xFF)
BLACK = (0x1A, 0x1A, 0x2E)
GOLD = (0xF2, 0xC1, 0x4E)

# (x0, y0, x1, y1, bottom corner radius, colour), drawn in order.
SHAPES = [(30.0, 33.0, 78.0, 37.5, 0.0, GOLD)]
for i in range(4):
    x0 = 30.0 + i * 12 + 0.6
    SHAPES.append((x0, 37.5, x0 + 10.8, 75.0, 2.2, WHITE))
for boundary in (42.0, 54.0):  # black keys between C-D and D-E
    SHAPES.append((boundary - 3.6, 37.5, boundary + 3.6, 60.0, 1.2, BLACK))


def inside(x, y, shape):
    x0, y0, x1, y1, r, _ = shape
    if x < x0 or x > x1 or y < y0 or y > y1:
        return False
    if r > 0 and y > y1 - r:
        for cx in (x0 + r, x1 - r):
            if (x < x0 + r and cx == x0 + r) or (x > x1 - r and cx == x1 - r):
                dx, dy = x - cx, y - (y1 - r)
                return dx * dx + dy * dy <= r * r
    return True


def png(path, size, view_origin, view_size, ss=2):
    big = size * ss
    scale = big / view_size
    buf = [bytearray(bytes(INDIGO) * big) for _ in range(big)]
    for shape in SHAPES:
        x0, y0, x1, y1, _, colour = shape
        px0, px1 = max(0, int((x0 - view_origin) * scale)), min(big, int((x1 - view_origin) * scale) + 1)
        py0, py1 = max(0, int((y0 - view_origin) * scale)), min(big, int((y1 - view_origin) * scale) + 1)
        c = bytes(colour)
        for py in range(py0, py1):
            vy = view_origin + (py + 0.5) / scale
            row = buf[py]
            for px in range(px0, px1):
                if inside(view_origin + (px + 0.5) / scale, vy, shape):
                    row[px * 3:px * 3 + 3] = c
    raw = bytearray()
    for y in range(size):
        raw.append(0)
        rows = [buf[y * ss + k] for k in range(ss)]
        for x in range(size):
            for ch in range(3):
                total = sum(r[(x * ss + j) * 3 + ch] for r in rows for j in range(ss))
                raw.append(total // (ss * ss))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(bytes(raw), 9)))
        f.write(chunk(b"IEND", b""))


def hexcolour(c):
    return "#FF%02X%02X%02X" % c


def vector_path(shape):
    x0, y0, x1, y1, r, _ = shape
    if r == 0:
        return f"M{x0:g},{y0:g}H{x1:g}V{y1:g}H{x0:g}Z"
    return (f"M{x0:g},{y0:g}H{x1:g}V{y1 - r:g}Q{x1:g},{y1:g} {x1 - r:g},{y1:g}"
            f"H{x0 + r:g}Q{x0:g},{y1:g} {x0:g},{y1 - r:g}Z")


def vector_xml():
    paths = "\n".join(
        f'    <path\n        android:fillColor="{hexcolour(s[5])}"\n        android:pathData="{vector_path(s)}" />' for s in SHAPES
    )
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Piano Trainer icon: four white keys, two black keys and a gold strip. Generated by
     scripts/make_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{paths}
</vector>
'''


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    # The visible 72-unit centre of the adaptive icon fills the square.
    png(f"{out}/preview-512.png", 512, view_origin=18.0, view_size=72.0)
    with open(f"{out}/ic_launcher_foreground.xml", "w") as f:
        f.write(vector_xml())
    print("done")
